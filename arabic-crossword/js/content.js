export const UNIT_COUNT = 100;

export function getUnit(id){
  return PUBLISHED_UNITS.find(u=>u.id===Number(id)) || null;
}

export function unitSlots(progress={}){
  return Array.from({length:UNIT_COUNT},(_,i)=>{
    const id=i+1, unit=getUnit(id);
    return {
      id,
      title:unit?.title || `الوحدة ${id}`,
      subtitle:unit?.subtitle || "قيد التحرير والتحقق",
      published:Boolean(unit),
      done:Boolean(progress?.units?.[id]?.completed),
      stars:progress?.units?.[id]?.stars || 0
    };
  });
}
