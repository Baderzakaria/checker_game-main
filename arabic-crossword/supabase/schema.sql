create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'لاعب',
  avatar text not null default '🧠',
  role text not null default 'player' check (role in ('player','editor','admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.player_states (
  user_id uuid primary key references auth.users(id) on delete cascade,
  state jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.categories (
  id text primary key,
  label_ar text not null,
  icon text,
  created_at timestamptz not null default now()
);

create table if not exists public.content_entries (
  id uuid primary key default gen_random_uuid(),
  canonical_answer text not null,
  grid_answer text not null,
  normalized_key text not null,
  aliases text[] not null default '{}',
  clue text not null,
  alternate_clues text[] not null default '{}',
  category_id text references public.categories(id),
  subcategory text,
  difficulty smallint not null default 3 check (difficulty between 1 and 10),
  media_type text not null default 'text',
  media_url text,
  fact_after_solve text,
  source_url text,
  source_title text,
  source_type text,
  license text,
  license_url text,
  attribution text,
  verification_status text not null default 'candidate'
    check (verification_status in ('candidate','review','approved','rejected','archived')),
  verified_by uuid references auth.users(id),
  verified_at timestamptz,
  time_sensitive boolean not null default false,
  reverify_after timestamptz,
  tags text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.units (
  id bigint generated by default as identity primary key,
  title_ar text not null,
  subtitle_ar text,
  sequence_no integer not null unique,
  status text not null default 'draft' check (status in ('draft','review','published','archived')),
  difficulty_floor numeric(4,2),
  difficulty_ceiling numeric(4,2),
  grid jsonb,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.unit_entries (
  unit_id bigint not null references public.units(id) on delete cascade,
  entry_id uuid not null references public.content_entries(id) on delete restrict,
  clue_number integer,
  direction text check (direction in ('H','V')),
  row_no integer,
  col_no integer,
  answer_order integer,
  primary key (unit_id, entry_id)
);

create table if not exists public.editorial_reviews (
  id bigint generated always as identity primary key,
  entry_id uuid not null references public.content_entries(id) on delete cascade,
  reviewer_id uuid references auth.users(id),
  decision text not null check (decision in ('approve','reject','changes')),
  notes text,
  created_at timestamptz not null default now()
);

