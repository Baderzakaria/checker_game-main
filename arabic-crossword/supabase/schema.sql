for select using (verification_status = 'approved');

drop policy if exists "published units readable" on public.units;
create policy "published units readable" on public.units
for select using (status = 'published');

drop policy if exists "published unit entries readable" on public.unit_entries;
create policy "published unit entries readable" on public.unit_entries
for select using (
  exists (
    select 1 from public.units u
    where u.id = unit_entries.unit_id and u.status = 'published'
  )
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data->>'display_name', split_part(new.email,'@',1), 'لاعب'))
  on conflict (id) do nothing;
  insert into public.player_states (user_id, state)
  values (new.id, '{}'::jsonb)
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

